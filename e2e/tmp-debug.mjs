import { chromium } from '@playwright/test'
const BASE = process.env.BASE_URL
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({ viewport: { width: 375, height: 812 } })
const page = await context.newPage()
page.on('console', message => console.log('console:', message.type(), message.text().slice(0, 300)))
page.on('pageerror', error => console.log('pageerror:', error.message))
page.on('requestfailed', request => console.log('requestfailed:', request.url().slice(0, 120), request.failure()?.errorText))
const response = await page.goto(BASE + '/', { waitUntil: 'domcontentloaded', timeout: 60000 }).catch(error => { console.log('goto error', error.message); return null })
console.log('status', response?.status())
await page.waitForTimeout(8000)
console.log('title', await page.title())
console.log('url', page.url())
console.log('body', (await page.locator('body').innerText().catch(() => '')).slice(0, 1200))
console.log('html head', (await page.content()).slice(0, 600))
await browser.close()
