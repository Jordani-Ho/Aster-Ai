export function normalizeText(input: string): string {
  // 只去掉空白并把全角数字转成半角，保留中文标点（匹配按子串进行，标点不影响）。
  const compact = input
    .replace(/\s+/g, '')
    .replace(/[０-９]/g, digit => String.fromCharCode(digit.charCodeAt(0) - 0xfee0))
  let simplified = ''
  for (const char of compact) simplified += TRADITIONAL_TO_SIMPLIFIED[char] ?? char
  return simplified
}
